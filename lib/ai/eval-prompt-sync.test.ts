import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { BUILTIN_AGENTS, BUILTIN_ORDER } from "@/lib/agents/templates";
import { MS_SCOPES } from "@/lib/ms/oauth";
import { zonedParts, zonedToUtc } from "@/lib/time/zoned";
import { accountContextOf } from "./account-context";
import { startAgentCreationTool, startUpgradeTool } from "./account-tools";
import { createReminderTool } from "./reminder-tools";
import { ROUTER_INSTRUCTIONS, buildSystemPrompt } from "./system-prompt";

/**
 * The Hebrew eval (scripts/hebrew-eval, a separate package without the "@/" aliases) runs the product's own prompt:
 * this test renders it for the eval's fixed user and clock — the context's "now", and 03:43 the same night for the
 * "מחר" after midnight cases — together with the account and reminder tool definitions, into
 * scripts/hebrew-eval/src/product-prompt.generated.ts. A prompt change without the regenerated file fails here.
 * Regenerate: pnpm vitest run lib/ai/eval-prompt-sync.test.ts -u
 */
interface EvalContextFile {
  now: string;
  timezone: string;
  profile: { name: string; business: string; type: string; email: string; morning_time: string; free_messages_remaining: number };
}

const context = JSON.parse(readFileSync(new URL("../../scripts/hebrew-eval/dataset/context.json", import.meta.url), "utf8")) as EvalContextFile;

function promptAt(now: Date): string {
  const p = context.profile;
  return buildSystemPrompt({
    name: p.name,
    businessName: p.business,
    businessType: p.type,
    timezone: context.timezone,
    morningTime: p.morning_time,
    connections: [{ provider: "microsoft", accountEmail: p.email, scopes: [...MS_SCOPES] }],
    profile: {},
    summary: null,
    facts: [],
    now,
    account: accountContextOf(null, p.free_messages_remaining, now),
    agentNames: BUILTIN_ORDER.map((r) => BUILTIN_AGENTS[r].name),
    gmailRead: false,
  });
}

const tool = (t: { name: string; description: string; input_schema: Record<string, unknown> }) => ({ name: t.name, description: t.description, input_schema: t.input_schema });

describe("the Hebrew eval runs the product prompt", () => {
  it("scripts/hebrew-eval/src/product-prompt.generated.ts is up to date", async () => {
    const day = new Date(context.now);
    const d = zonedParts(day, context.timezone);
    const night = zonedToUtc({ year: d.year, month: d.month, day: d.day, hour: 3, minute: 43 }, context.timezone);
    const out = [
      "// GENERATED by lib/ai/eval-prompt-sync.test.ts from the product's prompt — do not edit.",
      "// Regenerate after a prompt change: pnpm vitest run lib/ai/eval-prompt-sync.test.ts -u",
      `export const PRODUCT_SYSTEM_PROMPT_DAY = ${JSON.stringify(promptAt(day))};`,
      `export const PRODUCT_SYSTEM_PROMPT_SMALL_HOURS = ${JSON.stringify(promptAt(night))};`,
      `export const PRODUCT_ROUTER_INSTRUCTIONS = ${JSON.stringify(ROUTER_INSTRUCTIONS)};`,
      `export const PRODUCT_TOOLS = ${JSON.stringify([startUpgradeTool, startAgentCreationTool, createReminderTool].map(tool), null, 2)};`,
      "",
    ].join("\n");
    await expect(out).toMatchFileSnapshot("../../scripts/hebrew-eval/src/product-prompt.generated.ts");
  });
});
