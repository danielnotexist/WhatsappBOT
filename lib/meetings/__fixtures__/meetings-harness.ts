export interface TeamsMeetingFixture {
  id: string;
  joinUrl: string;
  transcripts: { id: string; createdDateTime: string; vtt: string }[];
}

/**
 * Graph online meetings on top of the Graph fixture: GET /me/onlineMeetings?$filter=JoinWebUrl eq '…',
 * /onlineMeetings/{id}/transcripts and …/transcripts/{id}/content?$format=text/vtt. `denied` answers 403 (the tenant's
 * policy / not the organiser).
 */
export function teamsFixture() {
  const fx = createGraphFixture();
  const state = { meetings: [] as TeamsMeetingFixture[], denied: false, calls: [] as string[] };
  const json = (body: unknown, status = 200) => new Response(JSON.stringify(body), { status, headers: { "content-type": "application/json" } });
  const fetchImpl = (async (input: string | URL | Request, init?: RequestInit) => {
    const url = new URL(String(input));
    const p = url.pathname.replace(/^\/v1\.0/, "");
    if (!p.startsWith("/me/onlineMeetings")) return fx.fetchImpl(input, init);
    state.calls.push(`${p}${url.search}`);
    if (state.denied) return json({ error: { code: "Forbidden", message: "Insufficient privileges" } }, 403);
    if (p === "/me/onlineMeetings") {
      const filter = url.searchParams.get("$filter") ?? "";
      const joinUrl = filter.match(/^JoinWebUrl eq '(.*)'$/)?.[1]?.replace(/''/g, "'");
      return json({ value: state.meetings.filter((m) => m.joinUrl === joinUrl).map((m) => ({ id: m.id, joinWebUrl: m.joinUrl })) });
    }
    const t = p.match(/^\/me\/onlineMeetings\/([^/]+)\/transcripts(?:\/([^/]+)\/content)?$/);
    const meeting = t ? state.meetings.find((m) => m.id === decodeURIComponent(t[1]!)) : undefined;
    if (!t || !meeting) return json({ error: { code: "NotFound", message: "not found" } }, 404);
    if (!t[2]) return json({ value: meeting.transcripts.map(({ id, createdDateTime }) => ({ id, createdDateTime, meetingId: meeting.id })) });
    const tr = meeting.transcripts.find((x) => x.id === decodeURIComponent(t[2]!));
    if (!tr) return json({ error: { code: "NotFound", message: "not found" } }, 404);
    return new Response(tr.vtt, { status: 200, headers: { "content-type": "text/vtt" } });
  }) as typeof fetch;
  const graph = new GraphClient({ getAccessToken: async () => "t", fetchImpl });
  return { fx, state, graph };
}

