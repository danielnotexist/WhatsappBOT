/**
 * A pro user (Dana) with WhatsApp, the Teams fixture as her Microsoft 365, and optionally the Google fixture; the
 * MeetingDeps of the jobs (the scripted mock as the model). `window`: she wrote a minute ago.
 */
export async function meetingSetup(opts: { at: Date; plan?: "pro" | "basic" | "trial"; msScopes?: string[]; google?: boolean; googleScopes?: string[]; microsoft?: boolean; window?: boolean; profile?: Record<string, unknown> }) {
  const h = makeHarness(opts.at);
  const created = await h.db.createUser("dana@levi-law.co.il");
  await h.db.mergeUserProfile(created.id, { onboarding: { step: "done", startedAt: "x" }, ...(opts.profile ?? {}) });
  await h.db.updateUserProfile(created.id, { name: "דנה לוי" });
  h.db.seedWaIdentity(created.id, "+972501234567");
  const plan = opts.plan ?? "pro";
  if (plan !== "trial") await h.db.upsertSubscription(created.id, { plan, status: "active", next_charge_at: new Date(opts.at.getTime() + 20 * 86_400_000).toISOString() });
  const teams = teamsFixture();
  const gfx = opts.google ? createGoogleFixture() : null;
  const google = gfx ? new GoogleClient({ getAccessToken: async () => "ya29", fetchImpl: gfx.fetchImpl }) : null;
  const workspace: MeetingWorkspace = {
    microsoft: async () => (opts.microsoft === false ? null : { graph: teams.graph, accountEmail: "dana@levi-law.co.il", scopes: opts.msScopes ?? MS_PRO_SCOPES }),
    google: async () => (google ? { google, accountEmail: "dana.levi@gmail.com", scopes: opts.googleScopes ?? GOOGLE_PRO_SCOPES } : null),
  };
  h.ctx.meetingWorkspace = workspace;
  const deps: MeetingDeps = { db: h.db, wa: h.wa, now: h.ctx.now, workspace, ai: h.ai, appUrl: "https://app.example.co.il" };
  if (opts.window !== false) {
    h.advance(-60_000);
    await h.db.insertMessage({ user_id: created.id, direction: "in", type: "text", text: "תודה", wa_message_id: "wamid.window" });
    h.advance(60_000);
  }
  const user = (await h.db.getUser(created.id))!;
  return { h, user, deps, teams, gfx, google, workspace };
}

